package com.service.tbterminal.inventory

data class UploadedProductMedia(
    val secureUrl: String,
    val publicId: String
)

enum class ImageMediaType(val extension: String, val mimeType: String) {
    JPEG("jpg", "image/jpeg"),
    PNG("png", "image/png"),
    WEBP("webp", "image/webp")
}

interface ProductMediaStorage {
    val isEnabled: Boolean
    fun ensureEnabled()
    suspend fun uploadProductPhoto(bytes: ByteArray, mediaType: ImageMediaType): UploadedProductMedia
    suspend fun destroyProductPhoto(publicId: String)
}

fun detectImageMediaType(bytes: ByteArray): ImageMediaType? {
    if (bytes.size >= 3 &&
        bytes[0] == 0xFF.toByte() &&
        bytes[1] == 0xD8.toByte() &&
        bytes[2] == 0xFF.toByte()
    ) {
        return ImageMediaType.JPEG
    }
    if (bytes.size >= 8 &&
        bytes[0] == 0x89.toByte() &&
        bytes[1] == 0x50.toByte() &&
        bytes[2] == 0x4E.toByte() &&
        bytes[3] == 0x47.toByte() &&
        bytes[4] == 0x0D.toByte() &&
        bytes[5] == 0x0A.toByte() &&
        bytes[6] == 0x1A.toByte() &&
        bytes[7] == 0x0A.toByte()
    ) {
        return ImageMediaType.PNG
    }
    if (bytes.size >= 12 &&
        bytes[0] == 'R'.code.toByte() &&
        bytes[1] == 'I'.code.toByte() &&
        bytes[2] == 'F'.code.toByte() &&
        bytes[3] == 'F'.code.toByte() &&
        bytes[8] == 'W'.code.toByte() &&
        bytes[9] == 'E'.code.toByte() &&
        bytes[10] == 'B'.code.toByte() &&
        bytes[11] == 'P'.code.toByte()
    ) {
        return ImageMediaType.WEBP
    }
    return null
}
